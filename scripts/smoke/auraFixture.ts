function renderProductCards(): string {
  return PRODUCTS.map(product => [
    `      <article class="product-card" id="product-${product.id}" data-category="${product.category}" data-name="${product.name}" data-price="${product.price}">`,
    `        <h2>${product.name}</h2>`,
    `        <p class="price">$${product.price}</p>`,
    `        <button class="add-to-cart-btn" type="button" data-product-id="product-${product.id}">Add to cart</button>`,
    '      </article>',
  ].join('\n')).join('\n');
}

