/**
 * Deterministic AURA e-commerce fixture generator.
 *
 * WHY THIS EXISTS
 * ---------------
 * `scripts/smoke/website-behavior-check.ts` reads a workspace at
 * `test/qwen-ecommerce-WxPTxO/AURA` by default. That directory is:
 *
 *   1. git-ignored (the whole `test` tree is ignored), so it is NOT part of
 *      the repository, and
 *   2. produced only by `scripts/smoke/high-end-ecommerce.ts`, which needs a
 *      **live Ollama model** to generate the site.
 *
 * The result was that `npm run test:website-behavior` — a stage inside the
 * `test:acceptance:safe` gate — could never pass on a clean checkout or on a
 * machine without a running local model. The gate crashed with
 * `ENOENT ... behavior-report.json` because it tried to write its report into
 * a directory that did not exist.
 *
 * This generator produces a **deterministic** fixture that satisfies exactly
 * the acceptance contract the live-generated project was supposed to satisfy.
 * It is not a mock of the checker: the checker still runs the real static
 * checks and the real fake-DOM runtime against real files. Only the
 * *provenance* of the input changes — from "generated by a local model" to
 * "committed deterministic source of truth".
 *
 * The fixture is written to a directory the caller chooses; the acceptance
 * gate provisions it on demand.
 */
import fs from 'node:fs';
import path from 'node:path';

/** File written next to the fixture to identify a generated project. */
export const FIXTURE_MARKER = '.aura-fixture.json';

/** Bump when the deterministic fixture content changes. */
export const FIXTURE_VERSION = '2';

