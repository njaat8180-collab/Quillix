const SCRIPT_JS = `/* AURA storefront behaviour: search, category filter, cart persistence. */
(function () {
  'use strict';

  var CART_KEY = 'aura-cart';

  function readCart() {
    try {
      var raw = localStorage.getItem(CART_KEY);
      var parsed = raw ? JSON.parse(raw) : [];
      return Array.isArray(parsed) ? parsed : [];
    } catch (error) {
      return [];
    }
  }

  function writeCart(items) {
    localStorage.setItem(CART_KEY, JSON.stringify(items));
  }

  function money(value) {
    return '$' + value.toFixed(2);
  }

  function productCards() {
    return Array.prototype.slice.call(document.querySelectorAll('.product-card'));
  }

  function applyFilters() {
    var search = document.getElementById('search-input');
    var category = document.getElementById('category-select');
    var term = ((search && search.value) || '').trim().toLowerCase();
    var selected = (category && category.value) || 'all';
    var cards = productCards();
    for (var i = 0; i < cards.length; i += 1) {
      var card = cards[i];
      var name = (card.getAttribute('data-name') || '').toLowerCase();
      var cardCategory = card.getAttribute('data-category') || '';
      var matchesTerm = !term || name.indexOf(term) !== -1;
      var matchesCategory = selected === 'all' || cardCategory === selected;
      card.style.display = matchesTerm && matchesCategory ? '' : 'none';
    }
  }

  function removeFromCart(id) {
    var items = readCart().filter(function (item) { return item.id !== id; });
    writeCart(items);
    renderCart();
  }

  function renderCart() {
    var items = readCart();
    var list = document.getElementById('cart-list');
    var count = document.getElementById('cart-count');
    var subtotal = document.getElementById('subtotal');
    list.innerHTML = '';
    var total = 0;
    for (var i = 0; i < items.length; i += 1) {
      var item = items[i];
      total += item.price;
      var row = document.createElement('li');
      row.className = 'cart-row';
      var label = document.createElement('span');
      label.className = 'cart-label';
      label.textContent = item.name + ' — ' + money(item.price);
      var remove = document.createElement('button');
      remove.type = 'button';
      remove.className = 'remove-from-cart-btn';
      remove.textContent = 'Remove';
      remove.setAttribute('data-product-id', item.id);
      // Bind directly on the button instead of relying on delegated bubbling.
      remove.addEventListener('click', function () {
        removeFromCart(item.id);
      });
      row.appendChild(label);
      row.appendChild(remove);
      list.appendChild(row);
    }
    count.textContent = String(items.length);
    subtotal.textContent = money(total);
  }

  document.addEventListener('DOMContentLoaded', function () {
    var search = document.getElementById('search-input');
    var category = document.getElementById('category-select');
    search.addEventListener('input', applyFilters);
    category.addEventListener('change', applyFilters);

    var buttons = document.querySelectorAll('.add-to-cart-btn');
    for (var i = 0; i < buttons.length; i += 1) {
      buttons[i].addEventListener('click', function (event) {
        var id = event.currentTarget.getAttribute('data-product-id');
        var card = document.getElementById(id);
        var name = card ? (card.getAttribute('data-name') || id) : id;
        var price = Number((card && card.getAttribute('data-price')) || 0) || 0;
        var items = readCart();
        items.push({ id: id, name: name, price: price });
        writeCart(items);
        renderCart();
      });
    }

    document.getElementById('checkout-button').addEventListener('click', function () {
      writeCart([]);
      renderCart();
    });

    applyFilters();
    renderCart();
  });
})();
`;

export interface FixtureOptions {
  /** Root directory that will contain the project folder. */
  root: string;
  /** Project folder name inside the root. Defaults to `AURA`. */
  project?: string;
}

/**
 * Write the deterministic AURA fixture and return the project directory.
 */
export function writeAuraFixture(options: FixtureOptions): string {
  const project = options.project || 'AURA';
  const projectRoot = path.join(options.root, project);
  fs.mkdirSync(projectRoot, { recursive: true });
  fs.writeFileSync(path.join(projectRoot, 'index.html'), INDEX_HTML, 'utf8');
  fs.writeFileSync(path.join(projectRoot, 'style.css'), STYLE_CSS, 'utf8');
  fs.writeFileSync(path.join(projectRoot, 'script.js'), SCRIPT_JS, 'utf8');
  // Marker: lets the acceptance gate detect a stale or hand-edited fixture and
  // regenerate the deterministic source of truth.
  fs.writeFileSync(path.join(projectRoot, FIXTURE_MARKER), FIXTURE_VERSION, 'utf8');
  return projectRoot;
}

